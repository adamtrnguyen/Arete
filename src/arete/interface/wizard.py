import json
import os
from collections.abc import Callable
from pathlib import Path

import typer

from arete.application.utils.common import detect_anki_paths

_BACKEND_CHOICES = {
    "": "auto",
    "1": "auto",
    "auto": "auto",
    "2": "ankiconnect",
    "ankiconnect": "ankiconnect",
    "3": "direct",
    "direct": "direct",
}


def run_init_wizard(
    *,
    input_fn: Callable[[str], str] = input,
    detect_paths: Callable[[], tuple[Path | None, Path | None]] = detect_anki_paths,
    home_dir: Path | None = None,
) -> bool:
    """Interactive setup wizard. Returns True on success/cancel, False on write error."""
    typer.echo("Welcome to arete Configuration Wizard!")
    typer.echo("This will verify your setup and create a ~/.config/arete/config.toml file.")
    typer.echo("")

    home = home_dir or Path.home()

    try:
        # 1. Vault Root
        vault_root = _ask_path(
            "Obsidian Vault Root",
            default=str(home / "Obsidian Vault"),
            input_fn=input_fn,
        )

        # 2. Anki Media
        _, detected_media = detect_paths()
        anki_media = _ask_path(
            "Anki Media Directory",
            default=str(detected_media) if detected_media else None,
            input_fn=input_fn,
        )

        # 3. Backend
        backend = _ask_backend(input_fn=input_fn)

        config_content = f"""# arete Configuration
# Generated by arete init

# Path to your Obsidian Vault
vault_root = {json.dumps(vault_root)}

# Path to Anki Media folder
anki_media_dir = {json.dumps(anki_media)}

# Anki Backend (auto, ankiconnect, direct)
backend = {json.dumps(backend)}

# Default verbosity (0=WARNING, 1=INFO, 2=DEBUG)
verbose = 1
"""

        target_path = home / ".config/arete/config.toml"
        target_path.parent.mkdir(parents=True, exist_ok=True)

        if target_path.exists():
            ovr = input_fn(f"\n{target_path} already exists. Overwrite? [y/N]: ").strip().lower()
            if ovr != "y":
                typer.echo("Aborted.")
                return True
    except (EOFError, KeyboardInterrupt):
        typer.echo("\nAborted.")
        return True

    try:
        with open(target_path, "w", encoding="utf-8") as f:
            f.write(config_content)
        typer.secho(f"\nConfiguration saved to {target_path}", fg="green")
        typer.echo("You can now run 'arete sync' without specifying media/vault flags.")
        return True
    except Exception as e:
        typer.secho(f"Error writing config: {e}", fg="red", err=True)
        return False


def _ask_backend(*, input_fn: Callable[[str], str] = input) -> str:
    typer.echo("\nSelect Anki Backend:")
    typer.echo("  1. auto (Try AnkiConnect, fall back to direct) [Default]")
    typer.echo("  2. ankiconnect (Requires Anki running + AnkiConnect add-on)")
    typer.echo("  3. direct (Direct DB access, requires Anki closed)")
    while True:
        choice = input_fn("Select backend [1]: ").strip().lower()
        if choice in _BACKEND_CHOICES:
            return _BACKEND_CHOICES[choice]
        typer.secho("Please choose 1 (auto), 2 (ankiconnect), or 3 (direct).", fg="yellow")


def _ask_path(
    label: str,
    default: str | None = None,
    *,
    input_fn: Callable[[str], str] = input,
) -> str:
    while True:
        prompt = f"{label} "
        if default:
            prompt += f"[{default}]: "
        else:
            prompt += ": "

        val = input_fn(prompt).strip()
        if not val and default:
            val = default

        if not val:
            typer.echo("Value required.")
            continue

        p = Path(os.path.expanduser(val)).resolve()
        if not p.exists():
            typer.secho(f"Warning: Path '{p}' does not exist.", fg="yellow")
            confirm = input_fn("Use anyway? [y/N]: ").strip().lower()
            if confirm == "y":
                return str(p)
        else:
            return str(p)
